/// Lower-case extension without the dot. `archive.tar.gz` yields `gz`: the
/// icon table is keyed by the last suffix, which is also what `unique_path`
/// treats as "the extension".
export function extensionOf(name: string): string {
  const base = baseName(name).toLowerCase()
  const dot = base.lastIndexOf('.')
  if (dot <= 0 || dot === base.length - 1) return ''
  return base.slice(dot + 1)
}

/// The final path component, accepting both separators.
export function baseName(path: string): string {
  const text = path.replace(/[\\/]+$/, '')
  const cut = Math.max(text.lastIndexOf('/'), text.lastIndexOf('\\'))
  return cut >= 0 ? text.slice(cut + 1) : text
}

/// Image/video/file decided from the MIME type first and the extension second.
/// A camera photo copied from a file manager often has an empty type, while a
/// `.bin` with `video/mp4` should still offer a player.
export function attachmentKind(name: string, mime = ''): AttachmentKind {
  const type = mime.trim().toLowerCase()
  if (type.startsWith('image/')) return 'image'
  if (type.startsWith('video/')) return 'video'
  const extension = extensionOf(name)
  if (IMAGE_EXTENSIONS.has(extension)) return 'image'
  if (VIDEO_EXTENSIONS.has(extension)) return 'video'
  return 'file'
}

/// The file-card icon, from the name alone: the issue's table is
/// extension-driven so a mislabelled MIME type does not change the drawing.
export function iconFor(name: string): ChatIconId {
  const extension = extensionOf(name)
  if (extension === '') return 'file'
  if (DOC_EXTENSIONS.has(extension)) return 'doc'
  if (SHEET_EXTENSIONS.has(extension)) return 'sheet'
  if (SLIDE_EXTENSIONS.has(extension)) return 'slides'
  if (extension === 'pdf') return 'pdf'
  if (ARCHIVE_EXTENSIONS.has(extension)) return 'archive'
  if (IMAGE_EXTENSIONS.has(extension)) return 'image'
  if (VIDEO_EXTENSIONS.has(extension)) return 'video'
  if (AUDIO_EXTENSIONS.has(extension)) return 'audio'
  if (TEXT_EXTENSIONS.has(extension)) return 'text'
  if (CODE_EXTENSIONS.has(extension)) return 'code'
  return 'file'
}

