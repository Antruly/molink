/// Pure chat helpers shared by the session chat pane and the host dock.
///
/// A chat message is still the plain `text` field of the existing chat hub.
/// Attachment messages carry a small JSON document there instead of a new wire
/// field, so an older core keeps storing and distributing them unchanged and
/// an older client simply shows the JSON. Everything in this module is DOM
/// free: the components add the camera, the file channel and the save picker.

export type AttachmentKind = 'image' | 'video' | 'file'

export type ChatIconId =
  | 'doc'
  | 'sheet'
  | 'slides'
  | 'pdf'
  | 'archive'
  | 'image'
  | 'video'
  | 'audio'
  | 'text'
  | 'code'
  | 'file'

/// One attachment descriptor. `thumb` is either a `data:` URL (small enough
/// for an old client, or generated by a peer that inlines it) or a path on the
/// host that owns the file; `src` is always the host-side path of the original.
export interface ChatAttachment {
  id: string
  name: string
  size: number
  mime: string
  kind: AttachmentKind
  thumb: string
  src: string
  /// Pixel size of the thumbnail / video frame, for the bubble aspect ratio.
  w: number
  h: number
  /// Video duration in seconds; 0 for other kinds.
  dur: number
}

export interface ChatPayload {
  type: 'chat'
  text: string
  attachments: ChatAttachment[]
}

/// The chat hub rejects text over 4096 bytes (see `api.cpp` and
/// `session_controller.cpp`). Attachment descriptors are deliberately tiny:
/// the media itself travels through the file channel.
export const CHAT_TEXT_LIMIT = 4096

export const MAX_CHAT_ATTACHMENT_BYTES = 200 * 1024 * 1024
export const MAX_CHAT_ATTACHMENTS = 9
/// Mirrors `clean_file_name` on the host, which truncates at 180 bytes. The
/// display name may be longer; only the name sent to the file channel is cut.
const MAX_STORED_NAME = 180
const MAX_DISPLAY_NAME = 200
const MAX_REFERENCE_LENGTH = 2048

