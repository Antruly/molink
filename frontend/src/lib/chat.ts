/// `1024` -> `1 KB`, `123456` -> `120.6 KB`. Binary units, one decimal, and
/// no dangling `.0`, which is what a file manager shows.
export function formatSize(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes < 0) return '—'
  const value = Math.floor(bytes)
  if (value < 1024) return `${value} B`
  const units = ['KB', 'MB', 'GB', 'TB', 'PB']
  let scaled = value / 1024
  let index = 0
  while (scaled >= 1024 && index < units.length - 1) {
    scaled /= 1024
    index += 1
  }
  const rounded = Math.round(scaled * 10) / 10
  return `${rounded} ${units[index]}`
}

/// A 24-hour clock, independent of the page locale so two bubbles separated by
/// a time separator always agree. An absent/invalid stamp renders empty.
export function formatTime(ts: number): string {
  if (!Number.isFinite(ts) || ts <= 0) return ''
  const date = new Date(ts)
  if (Number.isNaN(date.getTime())) return ''
  return `${String(date.getHours()).padStart(2, '0')}:${String(date.getMinutes()).padStart(2, '0')}`
}

export function isSameLocalDay(left: number, right: number): boolean {
  if (!Number.isFinite(left) || !Number.isFinite(right)) return false
  const a = new Date(left)
  const b = new Date(right)
  if (Number.isNaN(a.getTime()) || Number.isNaN(b.getTime())) return false
  return a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
}

/// Separator label: the clock for today, `YYYY-MM-DD HH:MM` otherwise. The
/// date is included so a chat reopened days later cannot look like it happened
/// this morning.
export function formatTimeSeparator(ts: number, now = Date.now()): string {
  const clock = formatTime(ts)
  if (clock === '') return ''
  if (isSameLocalDay(ts, now)) return clock
  const date = new Date(ts)
  const day = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
  return `${day} ${clock}`
}

export const CHAT_TIME_SEPARATOR_GAP_MS = 5 * 60 * 1000

/// A gap of more than five minutes starts a new group. `prev` of 0 is the
/// first message, which also gets a separator (the conversation start time).
export function shouldInsertTimeSeparator(
  prev: number,
  next: number,
  gapMs = CHAT_TIME_SEPARATOR_GAP_MS,
): boolean {
  if (!Number.isFinite(next) || next <= 0) return false
  if (!Number.isFinite(prev) || prev <= 0) return true
  return next - prev > gapMs
}

/// `0:07`, `1:05`, `1:02:03`; empty for unknown durations.
export function formatDuration(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds <= 0) return ''
  const total = Math.round(seconds)
  const hours = Math.floor(total / 3600)
  const minutes = Math.floor((total % 3600) / 60)
  const secs = total % 60
  if (hours > 0) {
    return `${hours}:${String(minutes).padStart(2, '0')}:${String(secs).padStart(2, '0')}`
  }
  return `${minutes}:${String(secs).padStart(2, '0')}`
}

const WINDOWS_RESERVED = new Set([
  'CON', 'PRN', 'AUX', 'NUL',
  'COM1', 'COM2', 'COM3', 'COM4', 'COM5', 'COM6', 'COM7', 'COM8', 'COM9',
  'LPT1', 'LPT2', 'LPT3', 'LPT4', 'LPT5', 'LPT6', 'LPT7', 'LPT8', 'LPT9',
])

/// A file name the host's `parse_relative_path` will accept. The host strips
/// more characters than we do, so this is deliberately conservative: replace
/// separators and Windows-forbidden characters, keep Unicode, strip control
/// characters, trailing dots/spaces and reserved device names.
export function safeChatFileName(name: string, fallback = 'file'): string {
  // eslint-disable-next-line no-control-regex
  let text = baseName(name.replace(/[\u0000-\u001f\u007f]/g, ''))
  text = text.replace(/[\\/:*?"<>|]/g, '_')
  text = text.replace(/^[ .]+|[ .]+$/g, '')
  if (text === '') text = fallback
  const dot = text.lastIndexOf('.')
  const stem = (dot > 0 ? text.slice(0, dot) : text).toUpperCase()
  if (WINDOWS_RESERVED.has(stem)) text = `_${text}`
  if (text.length > MAX_STORED_NAME) {
    const ext = extensionOf(text)
    const suffix = ext === '' ? '' : `.${ext}`
    const room = Math.max(1, MAX_STORED_NAME - suffix.length)
    text = text.slice(0, room) + suffix
  }
  return text === '' ? fallback : text
}

/// The path (relative to the host's default destination) an attachment takes.
/// The host creates the `chat/` folder underneath
/// `<download_root>/<remote>/<date>`; using a relative name means the viewer
/// never needs to know the host's configured storage root.
export function chatUploadName(name: string): string {
  return `chat/${safeChatFileName(name)}`
}

/// A short, filesystem-safe id for thumbnails and optimistic messages.
export function newAttachmentId(): string {
  const cryptoApi = globalThis.crypto
  if (cryptoApi && typeof cryptoApi.randomUUID === 'function') {
    return cryptoApi.randomUUID().replace(/-/g, '').slice(0, 16)
  }
  const random = Math.random().toString(16).slice(2, 10)
  return `${Date.now().toString(16)}${random}`.slice(0, 16)
}

export function chatThumbName(id: string): string {
  const clean = id.replace(/[^A-Za-z0-9_-]/g, '').slice(0, 40)
  return `chat/thumb-${clean === '' ? 'image' : clean}.webp`
}

function safeString(value: unknown): string {
  if (typeof value !== 'string') return ''
  return value.trim()
}

function safeNumber(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
    ? value
    : 0
}

/// Validate one descriptor from an incoming message. A missing `name` or
/// `size` rejects it (a nameless bubble cannot be saved or matched); every
/// other field is repaired instead of dropping the whole message.
export function validateChatAttachment(value: unknown): ChatAttachment | null {
  if (typeof value !== 'object' || value === null) return null
  const source = value as Record<string, unknown>
  const name = safeString(source.name)
  if (name === '') return null
  if (typeof source.size !== 'number' || !Number.isFinite(source.size) ||
      source.size < 0) {
    return null
  }
  const mime = safeString(source.mime)
  const kindValue = safeString(source.kind)
  const kind: AttachmentKind =
    kindValue === 'image' || kindValue === 'video' || kindValue === 'file'
      ? kindValue
      : attachmentKind(name, mime)
  const id = safeString(source.id) || newAttachmentId()
  const thumb = safeString(source.thumb).slice(0, MAX_REFERENCE_LENGTH)
  const src = safeString(source.src).slice(0, MAX_REFERENCE_LENGTH)
  return {
    id: id.slice(0, 64),
    name: name.slice(0, MAX_DISPLAY_NAME),
    size: Math.floor(source.size),
    mime: mime.slice(0, 200),
    kind,
    thumb,
    src,
    w: Math.floor(safeNumber(source.w)),
    h: Math.floor(safeNumber(source.h)),
    dur: safeNumber(source.dur),
  }
}

/// A descriptor this client is about to send. `size` is a file length so it is
/// always present; the caller supplies the kind/thumbnail fields.
export function makeChatAttachment(
  input: Omit<ChatAttachment, 'kind' | 'thumb' | 'src' | 'w' | 'h' | 'dur'> &
    Partial<Pick<ChatAttachment, 'kind' | 'thumb' | 'src' | 'w' | 'h' | 'dur'>>,
): ChatAttachment {
  return {
    id: input.id,
    name: input.name,
    size: Math.max(0, Math.floor(input.size)),
    mime: input.mime,
    kind: input.kind ?? attachmentKind(input.name, input.mime),
    thumb: input.thumb ?? '',
    src: input.src ?? '',
    w: input.w ?? 0,
    h: input.h ?? 0,
    dur: input.dur ?? 0,
  }
}

/// Parse the `text` field. Anything that is not our JSON envelope stays a
/// plain message, so ordinary chat and older peers are untouched.
export function parseChatPayload(text: string): ChatPayload | null {
  const trimmed = text.trim()
  if (!trimmed.startsWith('{') || !trimmed.endsWith('}')) return null
  let parsed: unknown
  try {
    parsed = JSON.parse(trimmed)
  } catch {
    return null
  }
  if (typeof parsed !== 'object' || parsed === null) return null
  const source = parsed as Record<string, unknown>
  if (source.type !== 'chat') return null
  const body = safeString(source.text)
  const attachments: ChatAttachment[] = []
  if (Array.isArray(source.attachments)) {
    for (const item of source.attachments) {
      if (attachments.length >= MAX_CHAT_ATTACHMENTS) break
      const attachment = validateChatAttachment(item)
      if (attachment) attachments.push(attachment)
    }
  }
  return { type: 'chat', text: body, attachments }
}

export function encodeChatPayload(payload: ChatPayload): string {
  return JSON.stringify({
    type: 'chat',
    text: payload.text,
    attachments: payload.attachments.map((attachment) => ({
      id: attachment.id,
      name: attachment.name,
      size: attachment.size,
      mime: attachment.mime,
      kind: attachment.kind,
      ...(attachment.thumb === '' ? {} : { thumb: attachment.thumb }),
      ...(attachment.src === '' ? {} : { src: attachment.src }),
      w: attachment.w,
      h: attachment.h,
      dur: attachment.dur,
    })),
  })
}

/// Whether the descriptor carries any preview reference. `thumb` is empty for
/// a file without a cover (and for a message from a peer that could not make
/// one); the bubble then shows the file card instead of waiting forever.
export function attachmentHasThumb(
  attachment: { thumb?: string | null },
): boolean {
  return (attachment.thumb ?? '').trim() !== ''
}

/// The source a bubble should paint. A locally generated `data:` URI wins: it
/// is already in the page and needs no file transfer. Next is the object URL
/// resolved from the downloaded `thumb-*.webp` file. `null` means neither is
/// available, which is the file-card state.
export function pickThumbSource(
  attachment: { thumb?: string | null },
  remoteThumbUrl?: string | null,
): string | null {
  const reference = (attachment.thumb ?? '').trim()
  if (reference.startsWith('data:')) return reference
  const remote = (remoteThumbUrl ?? '').trim()
  return remote === '' ? null : remote
}

export interface OutgoingChatMessage {
  /// The envelope handed to the core. Its `thumb` is the uploaded thumbnail's
  /// host path: the descriptor must stay well inside `CHAT_TEXT_LIMIT`, which
  /// a full `data:` URL usually exceeds.
  wire: ChatPayload
  /// `encodeChatPayload(wire)`, ready for `sendChat`/`postChat`.
  text: string
  /// The copy this client keeps in its own feed. Its `thumb` stays the
  /// generated `data:` URL, so the sender paints the picture immediately and
  /// can reuse it later without pulling the thumbnail back.
  local: ChatPayload
}

/// Build the two copies of an attachment message. The wire copy names the
/// uploaded `thumb-*.webp`; the local copy keeps the generated preview so the
/// sender's own bubble never falls back to the "tap to load" card.
export function buildOutgoingMessage(options: {
  attachment: ChatAttachment
  text?: string
  /// The generated `data:` preview to keep in the local copy.
  thumb?: string
  /// The wire thumbnail reference; defaults to `attachment.thumb`.
  wireThumb?: string
}): OutgoingChatMessage {
  const body = options.text ?? ''
  const wireThumb = options.wireThumb ?? options.attachment.thumb
  const wireAttachment: ChatAttachment = wireThumb === options.attachment.thumb
    ? options.attachment
    : { ...options.attachment, thumb: wireThumb }
  const preview = (options.thumb ?? '').trim()
  const localAttachment: ChatAttachment =
    preview.startsWith('data:') && preview !== wireThumb
      ? { ...wireAttachment, thumb: preview }
      : wireAttachment
  const wire: ChatPayload = {
    type: 'chat',
    text: body,
    attachments: [wireAttachment],
  }
  return {
    wire,
    text: encodeChatPayload(wire),
    local: { type: 'chat', text: body, attachments: [localAttachment] },
  }
}

/// UTF-8 bytes, not UTF-16 code units: the host measures the wire string.
export function chatTextBytes(text: string): number {
  return new TextEncoder().encode(text).length
}

export function fitsChatText(text: string): boolean {
  return chatTextBytes(text) <= CHAT_TEXT_LIMIT
}

/// Stable identity used to drop the optimistic copy once the core echoes the
/// message back. Attachment ids are unique; plain text falls back to its body.
export function chatPayloadKey(payload: ChatPayload): string {
  const ids = payload.attachments.map((attachment) => attachment.id).join(',')
  return `${payload.text}\u0000${ids}`
}

export function payloadFromMessageText(text: string): ChatPayload {
  return parseChatPayload(text) ?? { type: 'chat', text, attachments: [] }
}

/// Whether the last painted line is the bottom. A small threshold tolerates
/// sub-pixel layout and a bubble's own padding.
export function isNearBottom(
  scrollTop: number,
  scrollHeight: number,
  clientHeight: number,
  threshold = 48,
): boolean {
  return scrollHeight - scrollTop - clientHeight <= threshold
}

export const CHAT_HISTORY_PAGE = 40

/// How many of the newest loaded messages are painted. Older messages are
/// still in memory; the pane reveals another page as the user scrolls up.
export function historyPageCount(total: number, shown: number): number {
  if (!Number.isFinite(total) || total <= 0) return 0
  const safe = Number.isFinite(shown) ? Math.max(0, Math.floor(shown)) : 0
  return Math.min(Math.floor(total), Math.max(safe, 0))
}

export function historyWindowStart(total: number, shown: number): number {
  return Math.max(0, Math.floor(total) - historyPageCount(total, shown))
}

export function initialFor(name: string): string {
  const trimmed = name.trim()
  if (trimmed === '') return '?'
  return Array.from(trimmed)[0]?.toUpperCase() ?? '?'
}

const AVATAR_COLORS = [
  '#2dd4bf', '#60a5fa', '#a78bfa', '#fbbf24', '#fb7185', '#94a3b8',
]

/// A stable colour for an initial-letter avatar. Same sender, same hue.
export function avatarColorFor(seed: string): string {
  let hash = 0
  for (const char of seed) hash = (hash * 31 + char.codePointAt(0)!) >>> 0
  return AVATAR_COLORS[hash % AVATAR_COLORS.length]!
}

/// Join a folder and a name with the separator the folder already uses, so a
/// Windows host gets `C:\...\chat\a.txt` and never a mixed path.
export function joinHostPath(folder: string, name: string): string {
  if (folder === '') return name
  const separator = folder.includes('\\') ? '\\' : '/'
  const trimmed = folder.replace(/[\\/]+$/, '')
  if (trimmed === '') return separator + name
  return `${trimmed}${separator}${name}`
}

/// The pieces a host-side path is built from; separated out so the dock can
/// unit-test its layout without a DOM. `date` is `YYYY-MM-DD`.
export function hostChatDirectory(
  root: string,
  deviceId: string,
  date: string,
): string {
  if (root.trim() === '') return ''
  const cleanRoot = root.replace(/[\\/]+$/, '')
  // eslint-disable-next-line no-control-regex
  let device = deviceId.trim().replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_')
  if (device === '' || device === '.' || device === '..') device = 'unknown'
  // eslint-disable-next-line no-control-regex
  const day = date.trim().replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_')
  return joinHostPath(joinHostPath(joinHostPath(cleanRoot, device), day), 'chat')
}

export function localDateString(when = new Date()): string {
  return `${when.getFullYear()}-${String(when.getMonth() + 1).padStart(2, '0')}-${String(when.getDate()).padStart(2, '0')}`
}

/// A display name for a file whose own name is empty (a pasted clipboard
/// image is the common case). The receiver rejects a nameless descriptor, so
/// one must be invented before the message is built.
export function fallbackAttachmentName(mime: string, id = ''): string {
  const suffix = id.replace(/[^A-Za-z0-9_-]/g, '').slice(0, 12)
  const tail = suffix === '' ? '' : `-${suffix}`
  const type = mime.trim().toLowerCase()
  if (type.startsWith('image/')) {
    const subtype = type.slice(6).split(';')[0]!.split('+')[0]!
      .replace(/[^a-z0-9]/g, '')
    const extension = subtype === '' || subtype === 'jpeg'
      ? subtype === 'jpeg' ? 'jpg' : 'png'
      : subtype
    return `image${tail}.${extension}`
  }
  if (type.startsWith('video/')) return `video${tail}.mp4`
  return `file${tail}.bin`
}

/// `File.name` when it has one, otherwise a type-derived name.
export function chatDisplayName(
  name: string,
  mime: string,
  id = '',
): string {
  const trimmed = name.trim()
  if (trimmed !== '') return trimmed
  return fallbackAttachmentName(mime, id)
}

/// Whether a received descriptor's host path may be opened. The host only ever
/// writes attachments under `<download_root>/<device>/<date>/chat/`, so a path
/// with traversal, a different root or no `chat/` segment is not something this
/// feature produced. The check matters because the descriptor comes from the
/// peer: without it a chat message could name any file the core can read.
export function isAllowedAttachmentPath(root: string, path: string): boolean {
  const trimmedRoot = root.trim()
  const trimmedPath = path.trim()
  if (trimmedRoot === '' || trimmedPath === '') return false
  const normalize = (value: string) =>
    value.replace(/\\/g, '/').replace(/\/+$/, '')
  const base = normalize(trimmedRoot)
  const full = normalize(trimmedPath)
  if (base === '') return false
  // Windows paths (drive or UNC) are case-insensitive; POSIX is not.
  const windows = /^[A-Za-z]:/.test(trimmedRoot) ||
    trimmedRoot.startsWith('\\\\') ||
    trimmedRoot.includes('\\')
  const left = windows ? base.toLowerCase() : base
  const right = windows ? full.toLowerCase() : full
  if (!right.startsWith(`${left}/`)) return false
  const rest = full.slice(base.length + 1).split('/')
  if (rest.some((segment) => segment === '' || segment === '.' || segment === '..')) {
    return false
  }
  const chat = rest.findIndex((segment) => segment.toLowerCase() === 'chat')
  // `chat` must be a folder, not the file itself.
  return chat >= 0 && chat < rest.length - 1
}
